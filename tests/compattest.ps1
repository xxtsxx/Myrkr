# MUTATION - applied, run, and the stated check observed to fail.
#
#   macros.inc: HDR_VERSION 6 -> 7, which is literally what phase B does.
#     -> every check in section 1 FAILS with exit 4 ("not a valid Myrkr
#        container"), and section 0 still passes - the fixtures are untouched,
#        it is the reader that stopped accepting them. That is the whole
#        failure this file exists to make impossible to ship unnoticed, and it
#        is exactly what will happen the moment phase B bumps the version
#        without adding the dispatch to go with it.
#
#   pack.asm / cmd.asm: route ir_version and oc_version back to ir_corrupt and
#   oc_corrupt, i.e. undo the version-mismatch message.
#     -> "another format version says so" FAILS: the container is reported as
#        corrupt, which is what it said before 1.0.73.
#
#   macros.inc: HDR_VERSION_MIN 6 -> 7, i.e. drop support for the old format.
#     -> every check in section 1 FAILS, this time with the version message
#        rather than with "corrupt" - the 1.0.74 shape of the same disaster, and
#        the reason MIN is a constant somebody has to move deliberately.
#
#   pack.asm, entry_stream_open: replace `jb eso_len` with `jmp eso_len`'s
#   opposite - i.e. put the segment in the AAD for EVERY version.
#     -> every version-6 check FAILS with exit 3 (authentication failed): their
#        entries were sealed over 88 bytes of AAD and are now being read over
#        92. The mirror image - never adding the segment - is invisible to a
#        round-trip and is what the v8 fixtures are frozen for.
#
#   macros.inc: HDR_VERSION 8 -> 7, i.e. the writer never moved on.
#     -> "this build writes version 7" FAILS. Everything else still passes,
#        which is exactly why that check is there: a build that had quietly lost
#        the new version would otherwise look perfectly healthy.
# =============================================================================
if ($fail -gt 0) { "$fail FAILURE(S)"; exit 1 } else { "compattest: all checks passed"; exit 0 }
